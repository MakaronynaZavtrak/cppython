# --- целые числа и приоритет операций ---
print("2 + 3 * 4       =", 2 + 3 * 4)
print("(2 + 3) * 4     =", (2 + 3) * 4)
print("17 // 5         =", 17 // 5)      # целочисленное деление
print("17 % 5          =", 17 % 5)       # остаток
print("10 / 4          =", 10 / 4)       # деление -> float
print("2 ** 10         =", 2 ** 10)

# --- большие числа (произвольная точность) ---
factorial = 1
i = 1
while i <= 20:
    factorial *= i
    i += 1
print("20!             =", factorial)
print("2 ** 100        =", 2 ** 100)

# --- унарные операции ---
x = -5
print("-(-x)           =", -(-x))

# --- составное присваивание ---
total = 100
total += 50
total -= 20
total //= 2
print("total           =", total)

# --- побитовые операции ---
print("12 | 10         =", 12 | 10)
print("12 & 10         =", 12 & 10)
print("12 ^ 10         =", 12 ^ 10)

# --- сравнения, включая цепочки ---
print("3 < 5 <= 5      =", 3 < 5 <= 5)   # цепочка сравнений
print("1 == 1 != 2     =", 1 == 1 != 2)

# --- булева логика ---
print("True and False  =", True and False)
print("True or False   =", True or False)
print("not True        =", not True)

# --- float ---
print("3.5 + 1.5       =", 3.5 + 1.5)
print("2.0 * 2.0       =", 2.0 * 2.0)

