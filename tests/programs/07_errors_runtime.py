#    - затем выводится traceback из трёх кадров
#      (<module> -> compute -> divide) с кареткой под "a / b";
#    - последняя print-строка НЕ выполняется, потому что
#      исключение прерывает выполнение всего модуля.
#  Запуск:  cppython 07_errors_runtime.py
