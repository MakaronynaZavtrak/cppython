print("шаг 1: старт")


def divide(a, b):
    result = a / b          # <-- здесь произойдёт деление на ноль
    return result


def compute(x):
    print("шаг 3: внутри compute, сейчас будет деление на 0")
    return divide(x, 0)     # передаём 0 делителем


print("шаг 2: перед вызовом compute")

# Следующая строка порождает traceback из трёх кадров:
#   <module>  ->  compute  ->  divide
answer = compute(42)

# Сюда исполнение уже не дойдёт:
print(">>> эту строку ты не увидишь <<<")
